def build_writer_prompt(
    *,
    category: str,
    issue: str,
    article_analysis: dict[str, Any],
) -> str:
    analysis_json = json.dumps(
        article_analysis,
        ensure_ascii=False,
        indent=2,
    )

    return f"""
다음 기사 분석 결과를 바탕으로 HRD 뉴스레터를 작성하세요.

[뉴스레터 정보]
카테고리: {category}
발행호수: {issue}

[기사 분석 결과]
{analysis_json}

[작성 지시]
1. 전체 글은 SBAC 흐름을 따르세요.
2. 처음 읽는 사람도 이해할 수 있게 쓰세요.
3. 전문 용어는 처음 등장할 때 짧게 설명하세요.
4. 문장은 짧게 쓰세요.
5. 쉼표를 과하게 사용하지 마세요.
6. 이모지는 의미를 구분할 때 사용하세요.
7. 기사별 요약은 입력 기사 순서대로 작성하세요.
8. 교육 기획 포인트는 실제 설계에 활용할 수 있게 쓰세요.
9. 기사에 없는 사실은 추가하지 마세요.
10. JSON 구조만 출력하세요.
""".strip()
